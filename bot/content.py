@dataclass(frozen=True)
class Choice:
    id: str
    label: str
    correct: bool
    reaction: str


@dataclass(frozen=True)
class Reward:
    stamps: tuple[str, ...]
    caption: str
    photos: tuple[str, ...] = ()
    note: str = ""


@dataclass(frozen=True)
class Beat:
    id: str
    kind: str  # quiz, walk, final
    audio_title: str
    photos: tuple[str, ...]
    audio: str | None
    intro: str
    question: str | None = None
    choices: tuple[Choice, ...] = ()
    reward: Reward | None = None
    continue_label: str = "Дальше 👣"

    def choice(self, choice_id: str) -> Choice | None:
        for item in self.choices:
            if item.id == choice_id:
                return item
        return None

    def message(self, task_only: bool = False) -> str:
        if task_only and self.question:
            return self.question
        parts = [part for part in (self.intro, self.question) if part]
        return "\n\n".join(parts)


def _quiz(
    beat_id: str,
    title: str,
    photos: tuple[str, ...],
    audio: str,
    intro: str,
    question: str,
    choices: tuple[Choice, ...],
    reward: Reward,
) -> Beat:
    return Beat(
        id=beat_id,
        kind="quiz",
        audio_title=title,
        photos=photos,
        audio=audio,
        intro=intro,
        question=question,
        choices=choices,
        reward=reward,
    )


def _walk(
    beat_id: str,
    title: str,
    photos: tuple[str, ...],
    audio: str,
    intro: str,
) -> Beat:
    return Beat(
        id=beat_id,
        kind="walk",
        audio_title=title,
        photos=photos,
        audio=audio,
        intro=intro,
    )


