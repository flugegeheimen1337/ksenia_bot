def media_paths() -> tuple[str, ...]:
    paths = [START_PHOTO, PASSPORT_COVER, SPREAD]
    for beat in BEATS:
        paths.extend(beat.photos)
        if beat.audio:
            paths.append(beat.audio)
        if beat.reward:
            paths.extend(beat.reward.stamps)
            paths.extend(beat.reward.photos)
    return tuple(dict.fromkeys(paths))


def validate() -> None:
    from bot.config import MEDIA_DIR

    missing = [item for item in media_paths() if not (MEDIA_DIR / item).is_file()]
    if missing:
        raise SystemExit("Не хватает файлов: " + ", ".join(missing))
    if len(WELCOME) > 1000:
        raise SystemExit("Приветствие длиннее подписи к фото")
    if len(SPREAD_CAPTION) > 1000:
        raise SystemExit("Подпись паспорта длиннее 1000 знаков")
    for beat in BEATS:
        if len(beat.message()) > 4000:
            raise SystemExit(f"Текст {beat.id} длиннее 4000 знаков")
        for choice in beat.choices:
            if len(choice.label) > 64:
                raise SystemExit(f"Кнопка {beat.id}/{choice.id} длиннее 64 знаков")
            if len(f"a:{beat.id}:{choice.id}".encode()) > 64:
                raise SystemExit(f"callback {beat.id} слишком длинный")
        if beat.kind == "quiz":
            correct = [item for item in beat.choices if item.correct]
            if len(correct) != 1 or beat.reward is None or not beat.reward.stamps:
                raise SystemExit(f"У задания {beat.id} должен быть один верный ответ и штамп")
            if len(beat.reward.caption) > 1000:
                raise SystemExit(f"Подпись штампа {beat.id} длиннее 1000 знаков")
        elif beat.kind == "walk" and (beat.choices or beat.reward):
            raise SystemExit(f"Переход {beat.id} не должен содержать задание")
        elif beat.kind == "final" and beat.choices:
            raise SystemExit("У финала не должно быть вариантов ответа")
